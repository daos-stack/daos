#!/bin/bash
# Renders a ticket-specific env.sh and inventory.yml into a ticket directory,
# with build/install paths unique to that ticket so multiple tickets can be
# built/tested independently on the same shared cluster without clobbering
# each other. Pure local file generation -- no ssh/ansible interaction.
#
# Usage:
#   generate-daos-env.sh --ticket DAOS-NNNNN --worktree /path/to/worktree/daos [--force] [--dry-run]
#
# Flags:
#   --ticket DAOS-NNNNN   Ticket ID (required; normalizes daos-17321/17321 -> DAOS-17321)
#   --worktree PATH       Path to the ticket's DAOS source worktree (required;
#                         becomes DAOS_SRC / daos_source_dir)
#   --force               Overwrite an existing env.sh/inventory.yml (default: skip,
#                         so hand-edited customizations -- CONT_OPTS, POOL_OPTS,
#                         checksum settings, etc. -- are never silently clobbered)
#   --dry-run             Print what would be generated without writing anything
#
# Env overrides:
#   DAOS_TICKETS_DIR       Base directory for per-ticket workspaces (default: ~/work/tickets/daos-jira)
#   DAOS_SHARED_WORKSPACE  Shared DAOS_WORKSPACE to reuse prereqs from (default: /scratch/$USER/daos-install)
#
# After generating, see the ticket's README.md for the full workflow:
#   generate-daos-env.sh (this script) -> ansible-playbook (manual) -> build-daos.sh -> tests

set -euo pipefail

SCRIPT_DIR="$(realpath "$(dirname "${BASH_SOURCE[0]}")")"
ALT_PREFIX_HELPER="$SCRIPT_DIR/compute-daos-alt-prefix.sh"

DAOS_TICKETS_DIR="${DAOS_TICKETS_DIR:-$HOME/work/tickets/daos-jira}"
DAOS_SHARED_WORKSPACE="${DAOS_SHARED_WORKSPACE:-/scratch/$USER/daos-install}"

TICKET=""
WORKTREE=""
FORCE=0
DRY_RUN=0

usage() {
cat <<'EOF'
Usage:
  generate-daos-env.sh --ticket DAOS-NNNNN --worktree /path/to/worktree/daos [--force] [--dry-run]

Flags:
  --ticket DAOS-NNNNN   Ticket ID (required)
  --worktree PATH       Path to the ticket's DAOS source worktree (required)
  --force               Overwrite an existing env.sh/inventory.yml
  --dry-run             Print planned actions without writing anything

Env overrides:
  DAOS_TICKETS_DIR       Base directory for per-ticket workspaces (default: ~/work/tickets/daos-jira)
  DAOS_SHARED_WORKSPACE  Shared DAOS_WORKSPACE to reuse prereqs from (default: /scratch/$USER/daos-install)
EOF
}

normalize_ticket() {
local t
t="$(echo "$1" | tr '[:lower:]' '[:upper:]')"
if [[ "$t" =~ ^[0-9]+$ ]]; then
t="DAOS-$t"
fi
echo "$t"
}

while [[ $# -gt 0 ]]; do
case "$1" in
--ticket) TICKET="$2"; shift 2 ;;
--worktree) WORKTREE="$2"; shift 2 ;;
--force) FORCE=1; shift ;;
--dry-run) DRY_RUN=1; shift ;;
--help|-h) usage; exit 0 ;;
*) echo "generate-daos-env.sh: [ERROR] unknown argument: $1" >&2; usage >&2; exit 1 ;;
esac
done

if [[ -z "$TICKET" || -z "$WORKTREE" ]]; then
echo "generate-daos-env.sh: [ERROR] --ticket and --worktree are both required" >&2
exit 1
fi

TICKET="$(normalize_ticket "$TICKET")"
if [[ ! "$TICKET" =~ ^DAOS-[0-9]+$ ]]; then
echo "generate-daos-env.sh: [ERROR] invalid ticket ID: $TICKET (expected DAOS-NNNNN)" >&2
exit 1
fi
TICKET_LC="$(echo "$TICKET" | tr '[:upper:]' '[:lower:]')"

TICKET_DIR="$DAOS_TICKETS_DIR/$TICKET"
ENV_FILE="$TICKET_DIR/env.sh"
INVENTORY_FILE="$TICKET_DIR/inventory.yml"

DAOS_BUILD="/var/tmp/daos-build-$TICKET_LC"
DAOS_WORKSPACE="/scratch/$USER/daos-install-$TICKET_LC"

ALT_PREFIX=""
if [[ -x "$ALT_PREFIX_HELPER" ]]; then
ALT_PREFIX="$("$ALT_PREFIX_HELPER" "$DAOS_SHARED_WORKSPACE/install/lib/daos/.build_vars.sh")"
else
echo "generate-daos-env.sh: [WARN] $ALT_PREFIX_HELPER not found -- daos_alt_prefix will be empty (prereqs will be rebuilt from scratch for this ticket)" >&2
fi

if [[ "$DRY_RUN" -eq 1 ]]; then
echo "generate-daos-env.sh: [INFO] (dry-run) would write $ENV_FILE"
echo "generate-daos-env.sh: [INFO] (dry-run) would write $INVENTORY_FILE"
echo "generate-daos-env.sh: [INFO] (dry-run) DAOS_BUILD=$DAOS_BUILD DAOS_WORKSPACE=$DAOS_WORKSPACE"
echo "generate-daos-env.sh: [INFO] (dry-run) daos_alt_prefix=$ALT_PREFIX"
exit 0
fi

mkdir -p "$TICKET_DIR"

if [[ -f "$ENV_FILE" && "$FORCE" -ne 1 ]]; then
echo "generate-daos-env.sh: [INFO] $ENV_FILE already exists -- leaving it untouched (use --force to regenerate)"
else
cat > "$ENV_FILE" <<EOF
# shellcheck disable=SC2034
# Generated by generate-daos-env.sh for $TICKET -- see README.md for the full workflow.
# Hand-edit freely (CONT_OPTS, POOL_OPTS, checksum settings, etc.); re-running
# generate-daos-env.sh without --force will not overwrite your changes.

BUILD_NODE=brd-216
LOGIN_NODE=brd-216
ADMIN_NODE=brd-216
SERVER_NODES="brd-[216-219]"
CLIENT_NODES=brd-216
ALL_NODES="\$SERVER_NODES,\$CLIENT_NODES,\$ADMIN_NODE"

DAOS_WORKSPACE=$DAOS_WORKSPACE
DAOS_INSTALL="\$DAOS_WORKSPACE/install"
DAOS_BUILD=$DAOS_BUILD
DAOS_SRC="$WORKTREE"

POOL_NAME=tank
POOL_OPTS="--user=$USER --group=$USER --size=80% --nsvc=1"

CONT_NAME=$TICKET_LC
CONT_OPTS="--sys-name=daos_server --type=POSIX --properties=rf:2"

DMG_BIN="\$DAOS_INSTALL/bin/dmg"
DMG_OPTS="-o /etc/daos/daos_control.yml"

DAOS_BIN="\$DAOS_INSTALL/bin/daos"

DDB_BIN="\$DAOS_INSTALL/bin/ddb"
DAOS_SCM_MNT_PATH="/mnt/daos0-$TICKET_LC"

DDB_TESTS_BIN="\$DAOS_INSTALL/bin/ddb_tests"
DDB_TESTS_MNT_PATH="/mnt/daos-$TICKET_LC"
DDB_TESTS_MNT_OPTS="-t tmpfs -o rw,noatime,size=16777216k,inode64,huge=always,mpol=prefer:0,uid=\$(id -u),gid=\$(id -g)"

DDB_UT_BIN="\$DAOS_INSTALL/bin/ddb_ut"

DTX_TESTS_BIN="\$DAOS_INSTALL/bin/dtx_tests"
DTX_TESTS_MNT_PATH="/mnt/daos-$TICKET_LC"
DTX_TESTS_MNT_OPTS="-t tmpfs -o rw,noatime,size=16777216k,inode64,huge=always,mpol=prefer:0,uid=\$(id -u),gid=\$(id -g)"

DTX_UT_BIN="\$DAOS_INSTALL/bin/dtx_ut"

VOS_TESTS_BIN="\$DAOS_INSTALL/bin/vos_tests"
VOS_TESTS_MNT_PATH="/mnt/daos-$TICKET_LC"
VOS_TESTS_MNT_OPTS="-t tmpfs -o rw,noatime,size=16777216k,inode64,huge=always,mpol=prefer:0,uid=\$(id -u),gid=\$(id -g)"

DFUSE_MNT_PATH="/tmp/dfuse_mnt"

VALGRIND_BIN="/usr/bin/valgrind"
VALGRIND_OPTS="--leak-check=full --show-reachable=yes --num-callers=20 --error-limit=no --fair-sched=try --suppressions=\$DAOS_SRC/utils/test_memcheck.supp --gen-suppressions=all"

ASAN_LIB=/lib64/libasan.so.6
CLIENT_ASAN_OPTIONS=halt_on_error=1:atexit=1:leak_check_at_exit=1:use_sigaltstack=1:detect_odr_violation=0:disable_coredump=0:handle_segv=2:handle_abort=2:handle_sigfpe=2:handle_sigill=2:handle_sigbus=2:detect_leaks=1:max_leaks=100000:print_stats=1

# Functional tests (run-ftest.sh): launch.py defaults, overridable per run with
# the script's --servers/--clients/--nvme/--scm-size/--provider options.
# The usual split of this lab: 3 test servers + 1 test client.
FTEST_SERVERS="brd-[217-219]"
FTEST_CLIENTS="brd-216"
# launch.py --nvme mode (auto, auto_md_on_ssd, auto_nvme, ...); empty = ram
# only -- the brd-21x nodes have no SPDK setup.sh, "auto" fails there.
FTEST_NVME=""
# launch.py --scm_size in GiB; needed by "class: ram" yamls without scm_size,
# which otherwise auto-size the ramdisk from the whole node memory.
FTEST_SCM_SIZE=""
FTEST_PROVIDER="ofi+tcp"
# Default launch.py test filters, space separated, used when run-ftest.sh is
# called without tests, e.g. "PoolCreateSlowSvc DmgPoolQueryRanks".
FTEST_TESTS=""
EOF
echo "generate-daos-env.sh: [INFO] wrote $ENV_FILE"
fi

if [[ -f "$INVENTORY_FILE" && "$FORCE" -ne 1 ]]; then
echo "generate-daos-env.sh: [INFO] $INVENTORY_FILE already exists -- leaving it untouched (use --force to regenerate)"
else
cat > "$INVENTORY_FILE" <<EOF
---
# Ansible inventory for $TICKET -- generated by generate-daos-env.sh.
#
# Run "provision-daos.sh" (symlinked into this ticket's dir; wraps
# ansible-playbook -i inventory.yml ftest.yml from the daos-tools
# utils/ansible/ftest/ directory) yourself when you want to (re)provision the
# cluster for this ticket. This is a manual, deliberate step: it deploys this
# ticket's daos-make.sh/daos-launch.sh into daos_runtime_dir below. By default
# it does NOT repoint the shared /etc/ld.so.conf.d entry or PAM default PATH
# (daos_client_manage_system_paths=false) -- build-daos.sh --activate is the
# deliberate way to make this ticket the live one for those, plus the
# daos_server.service/daos_agent.service systemd units. See the ticket's
# README.md for the full workflow and this repo's utils/ansible/ftest/README.md
# for background.

all:
  vars:
    daos_runtime_dir: $DAOS_WORKSPACE
    daos_launch_username: $USER
    daos_http_proxy: http://proxy.houston.hpecorp.net:8080
    daos_proxy_bypass: "localhost,127.0.0.1,.amslabs.hpecorp.net"
    daos_proxy_nofwd:
      - dnf
  children:
    daos_dev:
      vars:
        daos_source_dir: $WORKTREE
        daos_build_dir: $DAOS_BUILD
        daos_ofi_interface: eth0
        daos_alt_prefix: "$ALT_PREFIX"
      hosts:
        brd-216:
    daos_servers:
      hosts:
        brd-216:
        brd-217:
        brd-218:
        brd-219:
    daos_clients:
      hosts:
        brd-216:
EOF
echo "generate-daos-env.sh: [INFO] wrote $INVENTORY_FILE"
fi

README_FILE="$TICKET_DIR/README.md"
if [[ -f "$README_FILE" && "$FORCE" -ne 1 ]]; then
echo "generate-daos-env.sh: [INFO] $README_FILE already exists -- leaving it untouched (use --force to regenerate)"
else
cat > "$README_FILE" <<EOF
# $TICKET workspace

Working directory for [$TICKET](https://daosio.atlassian.net/browse/$TICKET).

**Cluster**: \`brd-216\` (build/dev/client node) plus \`brd-[217-219]\` (additional
DAOS server nodes). \`\$HOME\` is NFS-shared across all four, so source/build state
is visible everywhere.

## Isolation model

- **Build + unit tests are isolated per ticket**: this ticket has its own
  \`DAOS_BUILD\`/\`daos_build_dir\` (\`$DAOS_BUILD\`) and
  \`DAOS_INSTALL\`/\`daos_runtime_dir\` (\`$DAOS_WORKSPACE\`), so building/installing
  never collides with another ticket's. Third-party prereqs (ofi, ucx, mercury,
  pmdk, spdk, ...) are reused from the shared cluster install via
  \`daos_alt_prefix\`/scons \`ALT_PREFIX\` instead of being rebuilt from scratch.
  Standalone unit-test binaries (\`vos_tests\`, \`ddb_ut\`, etc.) resolve their
  dependencies via their own RPATH, not the shared system \`ld.so.cache\`, so they
  keep working regardless of what other tickets have done. \`provision-daos.sh\`
  (this ticket's ansible-playbook wrapper) also doesn't touch the shared
  \`/etc/ld.so.conf.d\`/PAM default \`PATH\` by default
  (\`daos_client_manage_system_paths=false\`).
- **Live multi-node cluster testing is NOT isolated** (same as it has always
  been): \`daos_server.service\`/\`daos_agent.service\` (systemd units), the
  activated \`/etc/ld.so.conf.d\` entry, the PAM default \`PATH\` (if you opt
  back in), and the \`daos_server_helper\`/\`dfuse\` binaries installed to
  \`/usr/bin\` are single, cluster-wide resources -- only one ticket can be
  "the" live one at a time (via \`build-daos.sh --activate\`). The PMEM/NVMe
  storage and network ports on \`brd-216..219\` are physically exclusive too,
  regardless of software configuration. Coordinate with anyone else using this
  cluster before running \`cleanup.sh\`/\`start-daos.sh\`, same as always.

## Workflow

1. \`env.sh\`, \`inventory.yml\` -- generated by \`generate-daos-env.sh\` (already
   done; hand-edit freely, e.g. \`CONT_OPTS\`/\`POOL_OPTS\`/checksum settings --
   re-running \`generate-daos-env.sh\` without \`--force\` won't overwrite them).
2. \`provision-daos.sh\` (from this ticket's dir; wraps \`ansible-playbook
   -i inventory.yml ftest.yml\` from \`daos-tools/utils/ansible/ftest/\`) --
   provisions the cluster nodes and generates this ticket's own
   \`daos-make.sh\`/\`daos-launch.sh\` into \`daos_runtime_dir\`. Does NOT
   repoint the shared ld.so.conf.d entry or PAM PATH by default -- only
   \`build-daos.sh --activate\` does that (see Isolation model above).
3. \`build-daos.sh --force --deps\` for a full build, or plain
   \`build-daos.sh\` for an incremental rebuild -- builds/installs DAOS
   into this ticket's isolated \`DAOS_INSTALL\`. Add \`--activate\` to also make
   this ticket the live one on the shared cluster (see Isolation model above).
4. Standalone unit tests (isolated, safe to run regardless of what's live):
   \`run-vos_tests.sh\`, \`run-ddb_ut.sh\`, \`run-ddb_tests.sh\`, \`run-dtx_ut.sh\`,
   \`run-dtx_tests.sh\`, \`run-go_unit.sh\`.
5. Live cluster lifecycle (exclusive across tickets): \`start-daos.sh\` to bring
   up a pool/container, \`stop-daos.sh\` to stop it, \`cleanup.sh\` for a full
   destructive reset. Requires step 3 with \`--activate\` first.
6. Functional tests (exclusive too): \`run-ftest.sh PoolCreateSlowSvc\` runs
   launch.py filters through this ticket's \`daos-launch.sh\`; \`FTEST_*\` in
   \`env.sh\` hold the defaults (test servers/clients, nvme mode, scm size,
   provider, default filters). Files under \`files/ftest/\` (a test under
   development, e.g. \`files/ftest/pool/my_test.py\` + \`.yaml\`) are installed on
   top of the install tree's \`TESTING/ftest/\` before each run, so they can be
   iterated on without rebuilding.

## Files

| File | Purpose |
|---|---|
| \`env.sh\` | Central environment file sourced by every script here: node names, \`DAOS_SRC\`/\`DAOS_BUILD\`/\`DAOS_WORKSPACE\`/\`DAOS_INSTALL\` (ticket-specific), pool/container names+options, binary paths, tmpfs mount options, valgrind/ASAN options, \`FTEST_*\` functional-test defaults. |
| \`inventory.yml\` | Ansible inventory for \`ansible-playbook ftest.yml\` (see \`daos-tools/utils/ansible/ftest/README.md\`). |
| \`provision-daos.sh\` | Provisions this ticket via ansible-playbook, without repointing the shared ld.so.conf.d/PAM PATH by default (see \`build-daos.sh --activate\`). |
| \`build-daos.sh\` | Builds/installs DAOS remotely via this ticket's generated \`daos-make.sh\`. |
| \`run-vos_tests.sh\` / \`run-ddb_ut.sh\` / \`run-ddb_tests.sh\` / \`run-dtx_ut.sh\` / \`run-dtx_tests.sh\` | Standalone cmocka unit-test suite runners. |
| \`run-go_unit.sh\` | Go control-plane linters + unit tests (\`src/control\`). |
| \`start-daos.sh\` / \`stop-daos.sh\` / \`cleanup.sh\` | Live cluster lifecycle (bring up/down a pool+container, full reset). |
| \`run-ftest.sh\` | Functional tests (avocado) through this ticket's \`daos-launch.sh\`, with the \`files/ftest/\` overlay; defaults from \`FTEST_*\` in \`env.sh\`. |
| \`files/\` | Per-host \`daos_server-<host>.yml\`/\`daos_control-<host>.yml\`/\`daos_agent-<host>.yml\` for \`start-daos.sh\` (not generated -- copy them with \`--skeleton-from\`), and the optional \`ftest/\` overlay for \`run-ftest.sh\`. |
EOF
echo "generate-daos-env.sh: [INFO] wrote $README_FILE"
fi

echo "$TICKET_DIR"
