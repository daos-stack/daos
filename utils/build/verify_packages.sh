# Validate generated RPM packages produced by build_packages.sh.
#
# Checks:
# - RPM metadata and payload listing are readable.
# - Devel packages require matching non-devel package name and exact version.
# - Packages containing dynamically linked ELF executables require libc.
#
# Validation model:
# - Cache generated package names from all RPMs in the current build set.
# - For each -devel package, require the exact-version dependency defined in
#   the table for the selected distro.
# - For each RPM, inspect extracted executable ELF payload files; if dynamic,
#   ensure RPM Requires include libc soname dependency (libc.so.6* entries).
#
# Supported RPM layouts:
# - Root with nested subdirs: RPM_ROOT/deps/*.rpm and RPM_ROOT/daos/*.rpm
# - Flat root: RPM_ROOT/*.rpm
#
# Scope and limits:
# - This is a CI consistency gate for generated RPMs in one build set, not a
#   full dependency solver.
# - The devel dependency table covers packages generated by this RPM build;
#   unrelated system devel packages are outside its scope.
#
# Missing tooling, no RPM files found, or no devel dependency table for the
# selected suffix always fail regardless of the warning mode.
#
set -euo pipefail
shopt -s nullglob

usage() {
    cat <<EOF
Usage: ${0##*/} [options] RPM_ROOT

Validate generated RPM packages.

Options:
    --rpm-suffix=[el9|suse.lp155|suse.lp156]
                    RPM distribution suffix. Default: el9
    [ -Werror | -Wno-error ]
                    Select whether validation findings are treated as errors
                    or warnings. The options are mutually exclusive;
                    default: -Werror
    -h, --help      Show this help and exit

Exit codes:
    0 - Validation passed (or -Wno-error was used with validation findings).
    1 - Validation failed in -Werror mode or required tooling/setup is missing.
EOF
}

rpm_suffix=el9
mode=ERROR
mode_option=
positional_args=()
for arg in "$@"; do
    case "${arg}" in
        --rpm-suffix=*)
            rpm_suffix="${arg#*=}"
            ;;
        -Werror)
            [ -z "${mode_option}" ] || {
                echo "ERROR: -Werror and -Wno-error are mutually exclusive" >&2
                exit 1
            }
            mode_option=-Werror
            mode=ERROR
            ;;
        -Wno-error)
            [ -z "${mode_option}" ] || {
                echo "ERROR: -Werror and -Wno-error are mutually exclusive" >&2
                exit 1
            }
            mode_option=-Wno-error
            mode=WARNING
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        -* )
            echo "ERROR: unknown option '${arg}'" >&2
            usage >&2
            exit 1
            ;;
        *)
            positional_args+=("${arg}")
            ;;
    esac
done

if [ "${#positional_args[@]}" -ne 1 ]; then
    echo "ERROR: exactly one RPM_ROOT positional argument is required" >&2
    usage >&2
    exit 1
fi

RPM_ROOT="${positional_args[0]}"
if ! RPM_ROOT="$(cd "${RPM_ROOT}" 2>/dev/null && pwd)"; then
    echo "ERROR: RPM_ROOT is not an accessible directory: ${positional_args[0]}" >&2
    exit 1
fi

case "${rpm_suffix}" in
    el9 | suse.lp155 | suse.lp156)
        ;;
    *)
        echo "ERROR: --rpm-suffix must be el9, suse.lp155, or suse.lp156 (got: ${rpm_suffix})" >&2
        exit 1
        ;;
esac

for tool in rpm rpm2cpio cpio readelf; do
    if ! command -v "${tool}" >/dev/null 2>&1; then
        echo "ERROR: ${tool} command is required"
        exit 1
    fi
done

rpms=("${RPM_ROOT}"/deps/*.rpm "${RPM_ROOT}"/daos/*.rpm "${RPM_ROOT}"/*.rpm)
if [ "${#rpms[@]}" -eq 0 ]; then
    echo "ERROR: no RPM files found under ${RPM_ROOT}/deps, ${RPM_ROOT}/daos, or ${RPM_ROOT}"
    exit 1
fi

tmpdir="$(mktemp -d)"
trap 'rm -rf "${tmpdir}"' EXIT

DISTRO="${rpm_suffix}"
MODE="${mode}"

declare -i errors=0
declare -A pkg_names
declare -A pkg_present
declare -A devel_runtime

# Explicit devel to runtime package dependencies. These names are kept
# separate by distro because the same library has different RPM names.
case "${DISTRO}" in
    el9*)
        devel_runtime=(
            [argobots-devel]=argobots
            [daos-spdk-devel]=daos-spdk
            [isa-l-devel]=libisa-l
            [isa-l_crypto-devel]=libisa-l_crypto
            [libfabric-devel]=libfabric
            [mercury-devel]=mercury
            [libpmem-devel]=libpmem
            [libpmemobj-devel]=libpmemobj
            [daos-devel]=daos-client
        )
        ;;
    suse.lp15*)
        devel_runtime=(
            [libabt-devel]=libabt0
            [daos-spdk-devel]=daos-spdk
            [libisal-devel]=libisal2
            [libisal_crypto-devel]=libisal_crypto2
            [libfabric-devel]=libfabric1
            [mercury-devel]=mercury
            [libpmem-devel]=libpmem1
            [libpmemobj-devel]=libpmemobj1
            [daos-devel]=daos-client
        )
        ;;
    *)
        echo "ERROR: no devel dependency table for DISTRO=${DISTRO}"
        exit 1
        ;;
esac
# Records a validation issue; severity label follows MODE, but the error
# counter is always incremented so the final exit-code decision can use it.
report_error() {
    echo "${MODE}: $*"
    errors+=1
}

# Check whether RPM Requires contains a regex pattern.
# Args:
#   $1 path to RPM file
#   $2 extended regex pattern
# Returns:
#   0 if pattern exists in Requires output, 1 otherwise
rpm_requires_match() {
    local rpm_file="$1"
    local pattern="$2"

    rpm -qpR "${rpm_file}" | grep -Eq "${pattern}"
}

# Check for an exact package VERSION-RELEASE in Requires.
# Args:
#   $1 path to RPM file
#   $2 package name
#   $3 expected VERSION-RELEASE
# Returns:
#   0 if the package has an exact VERSION-RELEASE requirement, 1 otherwise
rpm_requires_version_match() {
    local rpm_file="$1"
    local required_pkg="$2"
    local expected_version="$3"
    local require
    local dep_pkg
    local operator
    local dep_version

    while IFS= read -r require; do
        read -r dep_pkg operator dep_version _ <<<"${require}"
        dep_pkg="${dep_pkg%,}"
        dep_pkg="${dep_pkg%%(*}"
        if [ "${dep_pkg}" = "${required_pkg}" ] &&
           [ "${operator:-}" = "=" ] &&
           [ "${dep_version:-}" = "${expected_version}" ]; then
            return 0
        fi
    done < <(rpm -qpR "${rpm_file}" || true)

    return 1
}

# Validate basic RPM integrity and cache Requires metadata.
# Args:
#   $1 path to RPM file
# Returns:
#   no direct return value; increments global error counter on failure
check_rpm_basic() {
    local rpm_file="$1"
    local pkg_name

    if ! rpm -K "${rpm_file}" >/dev/null; then
        report_error "rpm verification failed for ${rpm_file}"
        return
    fi

    if ! pkg_name="$(rpm -qp --qf '%{NAME}\n' "${rpm_file}")"; then
        report_error "cannot read package name from ${rpm_file}"
        return
    fi

    pkg_names["${rpm_file}"]="${pkg_name}"
    pkg_present["${pkg_name}"]=1

    if ! rpm -qpl "${rpm_file}" >/dev/null; then
        report_error "cannot list payload for ${rpm_file}"
    fi

}

# Extract RPM payload into target directory for local file inspection.
# Args:
#   $1 path to RPM file
#   $2 target extraction directory
# Returns:
#   no direct return value; command failure propagates via set -e
extract_rpm() {
    local rpm_file="$1"
    local target_dir="$2"

    mkdir -p "${target_dir}"
    (
        cd "${target_dir}"
        rpm2cpio "${rpm_file}" | cpio -idmu --quiet
    )
}

# Verify that -devel packages depend on a generated runtime package version.
# Args:
#   $1 path to RPM file
#   $2 package name
# Returns:
#   no direct return value; increments global error counter on mismatch
check_devel_runtime_dependency() {
    local rpm_file="$1"
    local pkg_name="$2"
    local runtime_pkg
    local expected_version

    if ! expected_version="$(rpm -qp --qf '%{VERSION}-%{RELEASE}\n' "${rpm_file}")"; then
        report_error "cannot determine package version for ${pkg_name} (${rpm_file})"
        return
    fi

    # fused-devel is intentionally built without fused runtime RPMs in this
    # pipeline, so requiring a generated runtime package would be a false fail.
    if [ "${pkg_name}" = "fused-devel" ]; then
        return
    fi

    runtime_pkg="${devel_runtime["${pkg_name}"]:-}"
    if [ -z "${runtime_pkg}" ]; then
        report_error "no runtime dependency mapping for ${pkg_name} on ${DISTRO}"
        return
    fi

    if [ -z "${pkg_present["${runtime_pkg}"]+x}" ]; then
        report_error "${pkg_name} requires missing runtime package ${runtime_pkg} in generated RPM set"
        return
    fi

    if ! rpm_requires_version_match "${rpm_file}" "${runtime_pkg}" "${expected_version}"; then
        report_error "${pkg_name} must require ${runtime_pkg} = ${expected_version}"
    fi
}

# Ensure dynamic ELF executable content results in libc Requires metadata.
# Args:
#   $1 path to RPM file
#   $2 package name
#   $3 extraction directory
# Returns:
#   no direct return value; increments global error counter on mismatch
check_binary_requires_libc() {
    local rpm_file="$1"
    local pkg_name="$2"
    local extract_dir="$3"
    local file_path
    local has_dynamic_elf_binary=0

    extract_rpm "${rpm_file}" "${extract_dir}"

    while IFS= read -r file_path; do

        # Treat ELF with an interpreter segment as an executable binary
        # (includes PIE binaries) and require dynamic dependencies.
        if readelf -h "${file_path}" >/dev/null 2>&1 &&
           readelf -l "${file_path}" 2>/dev/null | grep -q 'Requesting program interpreter' &&
           readelf -d "${file_path}" 2>/dev/null | grep -q '(NEEDED)'; then
            has_dynamic_elf_binary=1
            break
        fi
    done < <(find "${extract_dir}" -type f -perm /111 2>/dev/null)

    if [ "${has_dynamic_elf_binary}" -eq 1 ] &&
       ! rpm_requires_match "${rpm_file}" '^libc\.so\.6'; then
        report_error "${pkg_name} contains dynamically linked ELF binaries, but RPM" \
                     "requires metadata is missing libc soname dependency (libc.so.6*)"
    fi
}

echo "Verifying ${#rpms[@]} generated RPM(s) from ${RPM_ROOT} for ${DISTRO}"

for rpm_file in "${rpms[@]}"; do
    check_rpm_basic "${rpm_file}"
done

for rpm_file in "${rpms[@]}"; do
    pkg_name="${pkg_names["${rpm_file}"]:-}"
    [ -n "${pkg_name}" ] || continue

    work_dir="${tmpdir}/$(basename "${rpm_file}" .rpm)"
    rm -rf "${work_dir}"

    if [[ "${pkg_name}" == *-devel ]]; then
        check_devel_runtime_dependency "${rpm_file}" "${pkg_name}"
    fi

    check_binary_requires_libc "${rpm_file}" "${pkg_name}" "${work_dir}"
done

if [ "${errors}" -ne 0 ]; then
    if [ "${MODE}" = "WARNING" ]; then
        echo "RPM validation completed with ${errors} warning(s)"
        exit 0
    fi
    echo "RPM validation failed with ${errors} error(s)"
    exit 1
fi

echo "RPM validation passed"
