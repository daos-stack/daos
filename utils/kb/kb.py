import argparse
import json
import os
import re
import subprocess  # nosec
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "src"
KB = ROOT / "docs" / "kb"
GEN = KB / "generated"
GEN_HEADER = "<!-- Generated by utils/kb/kb.py extract; do not edit by hand. -->\n\n"

PRUNE_DIRS = {"vendor", "tests", "raft", ".git", "__pycache__"}
NON_C_MODULES = {"include", "tests", "proto", "control"}

# Owner module of each src/include/daos_srv header.
DAOS_SRV_OWNER = {
    "ad_mem": "common", "bio": "bio", "checker": "chk", "container": "container",
    "daos_chk": "chk", "daos_engine": "engine", "daos_mgmt_srv": "mgmt", "dtx_srv": "dtx",
    "evtree": "vos", "iv": "engine", "mgmt_tgt_common": "mgmt", "object": "object",
    "pool": "pool", "ras": "engine", "rdb": "rdb", "rebuild": "rebuild", "rsvc": "rsvc",
    "security": "security", "smd": "bio", "srv_csum": "object", "srv_obj_ec": "object",
    "vea": "vea", "vos": "vos", "vos_types": "vos",
}

C_KEYWORDS = {"if", "for", "while", "switch", "return", "sizeof", "do", "else", "case"}
FUNC_DEF_RE = re.compile(r"^(?:[A-Za-z_][\w \t*]*?[\s*])?([A-Za-z_]\w*)\s*\([^;]*$")
RPC_LIST_DEF_RE = re.compile(r"^#define\s+(\w+_PROTO_(CLI|SRV)_RPC_LIST)\b")
DSS_MODULE_RE = re.compile(r"^struct dss_module (\w+)\s*=\s*\{(.*?)\};", re.M | re.S)
DSS_FIELD_RE = re.compile(r"\.sm_(\w+)\s*=\s*([^,\n]+)")
INC_SRV_RE = re.compile(r'^#include\s+[<"]daos_srv/(\w+)\.h[>"]', re.M)
INC_REL_RE = re.compile(r'^#include\s+"((?:\.\./)+[\w./]+)"', re.M)
DRPC_ENUM_RE = re.compile(r"\b(DRPC_METHOD_\w+)\s*=\s*(\d+)")
DRPC_GO_RE = re.compile(r"\b(Method\w+)\s+\w+\s*=\s*C\.(DRPC_METHOD_\w+)")
DRPC_CASE_RE = re.compile(r"case\s+(DRPC_METHOD_\w+)\s*:\s*\n\s*(?:rc\s*=\s*)?(\w+)\(")


def rel(path):
    """Return a repo-relative posix path."""
    return Path(path).relative_to(ROOT).as_posix()


def walk(base, exts, prune=PRUNE_DIRS):
    """Yield files under base with one of the given extensions, pruning noisy dirs."""
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames[:] = sorted(d for d in dirnames if d not in prune)
        for name in sorted(filenames):
            if name.endswith(exts):
                yield Path(dirpath) / name


def read(path):
    """Read a source file, tolerating odd encodings."""
    return Path(path).read_text(encoding="utf-8", errors="replace")


def module_of(path):
    """Map a source path to its DAOS module (first dir under src/)."""
    parts = Path(path).relative_to(SRC).parts
    return parts[0] if len(parts) > 1 else None


def function_index():
    """Map C function name -> sorted list of files that define it."""
    index = defaultdict(set)
    for path in walk(SRC, (".c",), PRUNE_DIRS | {"control"}):
        for line in read(path).splitlines():
            if not line or line[0] in " \t#/{}*":
                continue
            match = FUNC_DEF_RE.match(line)
            if match and match.group(1) not in C_KEYWORDS:
                index[match.group(1)].add(rel(path))
    return {name: sorted(files) for name, files in index.items()}


def macro_body(lines, start):
    """Join a backslash-continued #define starting at lines[start]."""
    body = []
    i = start
    while True:
        line = lines[i]
        body.append(line.rstrip("\\ \t"))
        if not line.rstrip().endswith("\\"):
            return " ".join(body)
        i += 1


def split_x_entries(body):
    """Yield the top-level argument lists of every X(...) in a macro body."""
    pos = 0
    while True:
        start = body.find("X(", pos)
        if start < 0:
            return
        depth, args, cur = 0, [], []
        i = start + 1
        for i in range(start + 1, len(body)):
            char = body[i]
            if char == "(":
                depth += 1
                if depth == 1:
                    continue
            elif char == ")":
                depth -= 1
                if depth == 0:
                    break
            if char == "," and depth == 1:
                args.append("".join(cur).strip())
                cur = []
            else:
                cur.append(char)
        args.append("".join(cur).strip())
        pos = i + 1
        yield args


def extract_rpcs(funcs):
    """Parse every *_PROTO_{CLI,SRV}_RPC_LIST macro into RPC records."""
    rpcs = []
    for path in walk(SRC, (".h",), PRUNE_DIRS | {"control"}):
        lines = read(path).splitlines()
        for i, line in enumerate(lines):
            match = RPC_LIST_DEF_RE.match(line)
            if not match:
                continue
            for args in split_x_entries(macro_body(lines, i)):
                if len(args) < 4:
                    continue
                handler = args[3]
                rpcs.append({
                    "opcode": args[0],
                    "module": module_of(path),
                    "direction": "client->server" if match.group(2) == "CLI" else "server->server",
                    "handler": handler,
                    "handler_files": funcs.get(handler, []),
                    "collective": len(args) > 4 and args[4] != "NULL",
                    "defined_in": rel(path),
                })
    return rpcs


def extract_modules():
    """Parse every 'struct dss_module X = {...}' engine module registration."""
    mods = []
    for path in walk(SRC, (".c",), PRUNE_DIRS | {"control"}):
        for match in DSS_MODULE_RE.finditer(read(path)):
            fields = {k: v.strip() for k, v in DSS_FIELD_RE.findall(match.group(2))}
            mods.append({
                "symbol": match.group(1),
                "name": fields.get("name", "").strip('"'),
                "mod_id": fields.get("mod_id", ""),
                "init": fields.get("init", ""),
                "setup": fields.get("setup", ""),
                "file": rel(path),
                "module": module_of(path),
            })
    return sorted(mods, key=lambda m: m["name"])


def extract_deps():
    """Infer module -> module dependencies from #include directives."""
    deps = defaultdict(lambda: defaultdict(int))
    for path in walk(SRC, (".c", ".h"), PRUNE_DIRS | NON_C_MODULES):
        src_mod = module_of(path)
        text = read(path)
        targets = {DAOS_SRV_OWNER.get(h) for h in INC_SRV_RE.findall(text)}
        for inc in INC_REL_RE.findall(text):
            resolved = (path.parent / inc).resolve()
            if SRC in resolved.parents:
                targets.add(module_of(resolved))
        for dst in targets:
            if dst and dst != src_mod and dst not in NON_C_MODULES:
                deps[src_mod][dst] += 1
    return {src: dict(sorted(dsts.items())) for src, dsts in sorted(deps.items())}


def extract_drpc(funcs):
    """Join dRPC method IDs with their Go constants, Go callers and engine handlers."""
    ids = dict(DRPC_ENUM_RE.findall(read(SRC / "include/daos/drpc_modules.h")))
    go_const = {c: g for g, c in DRPC_GO_RE.findall(read(SRC / "control/lib/daos/drpc.go"))}
    callers = defaultdict(set)
    for path in walk(SRC / "control", (".go",)):
        if path.name.endswith("_test.go"):
            continue
        for name in set(re.findall(r"\bdaos\.(Method\w+)\b", read(path))):
            callers[name].add(rel(path))
    handlers = {}
    for path in walk(SRC, (".c",), PRUNE_DIRS | {"control"}):
        for method, func in DRPC_CASE_RE.findall(read(path)):
            handlers[method] = {"func": func, "files": funcs.get(func, [rel(path)])}
    out = []
    for method, num in sorted(ids.items(), key=lambda kv: int(kv[1])):
        gname = go_const.get(method, "")
        out.append({
            "method": method, "id": int(num), "go_const": gname,
            "go_callers": sorted(callers.get(gname, [])),
            "engine_handler": handlers.get(method, {}).get("func", ""),
            "engine_files": handlers.get(method, {}).get("files", []),
        })
    return out


FRONT_RE = re.compile(r"\A---\n(.*?)\n---\n", re.S)


def card_frontmatter():
    """Parse the simple 'key: value' / 'key: [a, b]' frontmatter of hand-written KB cards."""
    cards = []
    for path in sorted(KB.rglob("*.md")):
        if GEN in path.parents:
            continue
        match = FRONT_RE.match(read(path))
        if not match:
            continue
        meta = {"file": rel(path)}
        for line in match.group(1).splitlines():
            if ":" not in line:
                continue
            key, val = (s.strip() for s in line.split(":", 1))
            if val.startswith("["):
                meta[key] = [v.strip() for v in val.strip("[]").split(",") if v.strip()]
            else:
                meta[key] = val
        if "id" in meta:
            cards.append(meta)
    return cards


def code(text):
    """Wrap text in backticks for markdown tables."""
    return f"`{text}`" if text else ""


def render_rpcs(rpcs):
    """Render the RPC table grouped by module."""
    out = [GEN_HEADER, "# CaRT RPC opcodes by module\n\n",
           "Source: `*_PROTO_{CLI,SRV}_RPC_LIST` X-macros. client->server RPCs are sent by "
           "libdaos; server->server RPCs are engine-internal (collective = has corpc ops).\n"]
    by_mod = defaultdict(list)
    for rpc in rpcs:
        by_mod[rpc["module"]].append(rpc)
    for mod in sorted(by_mod):
        out.append(f"\n## {mod}\n\nDefined in {code(by_mod[mod][0]['defined_in'])}\n\n")
        out.append("| Opcode | Direction | Handler | Handler file | Collective |\n")
        out.append("|---|---|---|---|---|\n")
        for rpc in by_mod[mod]:
            files = ", ".join(code(f) for f in rpc["handler_files"])
            out.append(f"| {code(rpc['opcode'])} | {rpc['direction']} | {code(rpc['handler'])} "
                       f"| {files} | {'yes' if rpc['collective'] else ''} |\n")
    return "".join(out)


def render_modules(mods, deps):
    """Render engine module registrations and the include-derived dependency table."""
    out = [GEN_HEADER, "# Engine modules and dependencies\n\n",
           "## Engine modules (`struct dss_module`)\n\n",
           "Loaded by `daos_engine` (see `src/engine/module.c`).\n\n",
           "| Name | Module ID | Symbol | Init | File |\n|---|---|---|---|---|\n"]
    for mod in mods:
        out.append(f"| {mod['name']} | {code(mod['mod_id'])} | {code(mod['symbol'])} "
                   f"| {code(mod['init'])} | {code(mod['file'])} |\n")
    out.append("\n## Module dependencies (from `#include`)\n\n"
               "An edge A -> B means files in `src/A` include a `daos_srv/` header owned by B or a "
               "file under `src/B`. The number is how many files do so.\n\n"
               "| Module | Depends on |\n|---|---|\n")
    for src, dsts in deps.items():
        listed = ", ".join(f"{d} ({n})" for d, n in dsts.items())
        out.append(f"| {src} | {listed} |\n")
    users = defaultdict(list)
    for src, dsts in deps.items():
        for dst in dsts:
            users[dst].append(src)
    out.append("\n## Reverse dependencies (used by)\n\n| Module | Used by |\n|---|---|\n")
    for dst in sorted(users):
        out.append(f"| {dst} | {', '.join(sorted(users[dst]))} |\n")
    return "".join(out)


def render_drpc(drpc):
    """Render the control-plane <-> engine dRPC method table."""
    out = [GEN_HEADER, "# dRPC methods (daos_server <-> daos_engine)\n\n",
           "IDs from `src/include/daos/drpc_modules.h`; Go constants from "
           "`src/control/lib/daos/drpc.go`. 2xx are handled by the engine (`src/mgmt/srv.c`); "
           "3xx are engine -> daos_server notifications handled in Go.\n\n",
           "| ID | Method | Go const | Go callers | Engine handler | Handler file |\n",
           "|---|---|---|---|---|---|\n"]
    for item in drpc:
        callers = ", ".join(code(c) for c in item["go_callers"])
        files = ", ".join(code(f) for f in item["engine_files"])
        out.append(f"| {item['id']} | {code(item['method'])} | {code(item['go_const'])} "
                   f"| {callers} | {code(item['engine_handler'])} | {files} |\n")
    return "".join(out)


def build_graph(rpcs, mods, deps, drpc, cards):
    """Assemble a node/edge graph combining extracted facts and card frontmatter."""
    nodes, edges = {}, []

    def node(nid, kind, **attrs):
        nodes.setdefault(nid, {"id": nid, "kind": kind}).update(attrs)

    for src, dsts in deps.items():
        node(src, "module")
        for dst, weight in dsts.items():
            node(dst, "module")
            edges.append({"src": src, "dst": dst, "kind": "includes", "weight": weight})
    for mod in mods:
        node(mod["module"], "module", engine_module=mod["name"])
    for rpc in rpcs:
        rid = f"rpc:{rpc['opcode']}"
        node(rid, "rpc", direction=rpc["direction"], handler=rpc["handler"],
             handler_files=rpc["handler_files"])
        edges.append({"src": rpc["module"], "dst": rid, "kind": "handles_rpc"})
    for item in drpc:
        did = f"drpc:{item['method']}"
        node(did, "drpc", method_id=item["id"], handler=item["engine_handler"])
        if item["engine_handler"]:
            edges.append({"src": "mgmt", "dst": did, "kind": "handles_drpc"})
    for card in cards:
        node(card["id"], card.get("kind", "module"), card=card["file"])
        nodes[card["id"]]["kind"] = card.get("kind", "module")
    for card in cards:
        for key in ("depends_on", "used_by", "related"):
            for dst in card.get(key, []):
                node(dst, "module" if key != "related" else "concept")
                edges.append({"src": card["id"], "dst": dst, "kind": key, "from": "card"})
    edges.sort(key=lambda e: (e["src"], e["kind"], e["dst"]))
    return {"nodes": sorted(nodes.values(), key=lambda n: n["id"]), "edges": edges}


def generate():
    """Return {path: content} for every generated KB file."""
    funcs = function_index()
    rpcs = extract_rpcs(funcs)
    mods = extract_modules()
    deps = extract_deps()
    drpc = extract_drpc(funcs)
    graph = build_graph(rpcs, mods, deps, drpc, card_frontmatter())
    return {
        GEN / "rpcs.md": render_rpcs(rpcs),
        GEN / "modules.md": render_modules(mods, deps),
        GEN / "drpc.md": render_drpc(drpc),
        GEN / "graph.json": json.dumps(graph, indent=1, sort_keys=True) + "\n",
    }


def cmd_extract(_args):
    """Write generated files."""
    GEN.mkdir(parents=True, exist_ok=True)
    for path, content in generate().items():
        path.write_text(content, encoding="utf-8")
        print(f"wrote {rel(path)}")
    return 0


LINK_RE = re.compile(r"\[[^\]]*\]\(([^)\s]+)\)")
SCOPED_SYM_RE = re.compile(r"`([\w./-]+\.\w+)::([\w.]+)(?:\(\))?`")
BARE_SYM_RE = re.compile(r"`([A-Za-z_]\w*)\(\)`")
PATH_RE = re.compile(r"`((?:src|docs|utils|site_scons|ci|\.github)/[\w./-]*[\w/])`")


def kb_docs():
    """Hand-written files that the linter validates."""
    files = [p for p in KB.rglob("*.md") if GEN not in p.parents]
    files += sorted((ROOT / ".github" / "instructions").glob("*.md"))
    files += [p for p in [ROOT / ".github" / "copilot-instructions.md"] if p.exists()]
    files += sorted((ROOT / ".github" / "skills").rglob("*.md"))
    files += sorted((ROOT / "utils" / "kb" / "benchmark").glob("*.md"))
    return sorted(files)


def existing_words(words):
    """Return the subset of words that occur as whole words somewhere under src/."""
    if not words:
        return set()
    cmd = ["git", "-C", str(ROOT), "grep", "-h", "-o", "-w", "-F"]
    for word in sorted(words):
        cmd += ["-e", word]
    cmd += ["--", "src", ":!src/control/vendor", ":!src/rdb/raft"]
    result = subprocess.run(cmd, capture_output=True, text=True, check=False)  # nosec
    return set(result.stdout.split())


def cmd_lint(_args):
    """Check that every path / symbol referenced in the KB exists."""
    errors, bare = [], defaultdict(list)
    for doc in kb_docs():
        text = read(doc)
        where = rel(doc)
        for target in LINK_RE.findall(text):
            if re.match(r"^[a-z]+:", target) or target.startswith("#"):
                continue
            path = target.split("#", 1)[0]
            base = ROOT if path.startswith("/") else doc.parent
            if path and not (base / path.lstrip("/")).exists():
                errors.append(f"{where}: broken link {target}")
        for path in PATH_RE.findall(text):
            if not (ROOT / path).exists():
                errors.append(f"{where}: missing path {path}")
        for path, sym in SCOPED_SYM_RE.findall(text):
            name = sym.rsplit(".", 1)[-1]
            target = ROOT / path
            if not target.is_file():
                errors.append(f"{where}: missing file {path} (for {sym})")
            elif not re.search(rf"\b{re.escape(name)}\b", read(target)):
                errors.append(f"{where}: {name} not found in {path}")
        for sym in BARE_SYM_RE.findall(text):
            bare[sym].append(where)
    found = existing_words(set(bare))
    for sym, wheres in sorted(bare.items()):
        if sym not in found:
            errors.append(f"{wheres[0]}: symbol {sym}() not found under src/")
    for err in errors:
        print(err)
    print(f"kb lint: {len(kb_docs())} files, {len(errors)} problem(s)")
    return 1 if errors else 0


def cmd_check(args):
    """Fail if generated files are out of date, then lint."""
    stale = [rel(p) for p, c in generate().items()
             if not p.exists() or read(p) != c]
    for path in stale:
        print(f"stale: {path} (run utils/kb/kb.py extract)")
    return max(1 if stale else 0, cmd_lint(args))


def main():
    """Entry point."""
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("extract").set_defaults(func=cmd_extract)
    sub.add_parser("lint").set_defaults(func=cmd_lint)
    sub.add_parser("check").set_defaults(func=cmd_check)
    args = parser.parse_args()
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
